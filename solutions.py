def shopping_list(cook_book: list, person: int) -> list:
    result = [] # в этой переменной будет список покупок
    for dish in cook_book: # цикл по всем блюдам кулинарной книги
        dish_recipe = str(dish[0]) + ': ' # в эту переменную присваиваем заголовок блюда (он находится в dish[0])
        for num, ingredient in enumerate(dish[1], start = 1): # проходим по всем ингредиентам блюда (они находятся в dish[1])
            # не забудьте, что числа необходимо умножить на количество персон, а затем перевести в строку
            dish_recipe += f'{ingredient[0]} {str(ingredient[1] * person)} {ingredient[2]}' # собираем рецепт, соединяя ингредиенты через пробел.    
            if num < len(dish[1]): # если ингредиент не последний, добавить в коде ниже запятую после ингредиента
                dish_recipe += ', ' # добавить запятую после ингредиента
        result.append(dish_recipe) # добавить строку с заголовком блюда и его ингредиентами в список покупок
    # print(result) # раскомментируйте эту строку, если хотите проверить  результат вашего кода
    return result # не меняйте этот код

