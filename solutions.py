def unique_names(mentors:list) -> str:
    names = set()        # множество для хранения уникальных имён    
                                          
    for name in mentors :               # пройдите циклом по каждому преподавателю                                                     
        name_parts = name.split(" ")      # разделите полное имя на части по пробелу (имя и фамилия отдельно)
        name = name_parts[0]            # возьмите только имя
        names.add(name)                   # добавьте имя в множество

    sorted_names = list(names)  # преобразуйте множество names в список
    sorted_names = sorted(sorted_names)  # отсортируйте список по возрастанию, используя функцию sorted()
    result = ', '.join(sorted_names)     # объедините имена в строку через перечисление ", ". должно получиться "Адилет, Азамат, Александр, ..."
    print(result) # раскомментируйте эту строку, если хотите проверить результат вашего кода
    return result     # этот код изменять не нужно 

